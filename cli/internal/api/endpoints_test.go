package api

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// baselineRepoRoot walks up from this package's directory to the
// repository root (the directory containing docs/openapi/baseline.yaml).
func baselineRepoRoot(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	if err != nil {
		t.Fatalf("getwd: %v", err)
	}
	for i := 0; i < 10; i++ {
		if _, err := os.Stat(filepath.Join(dir, "docs", "openapi", "baseline.yaml")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	t.Fatal("docs/openapi/baseline.yaml not found above cli/internal/api")
	return ""
}

// baselinePaths extracts the top-level path keys of the spec's `paths:`
// section. The baseline is generated by springdoc, whose YAML layout is
// stable: two-space-indented `/api/...:` keys directly under `paths:`.
// If that layout ever changes, this scan fails loudly rather than
// silently passing.
func baselinePaths(t *testing.T) map[string]bool {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(baselineRepoRoot(t), "docs", "openapi", "baseline.yaml"))
	if err != nil {
		t.Fatalf("reading baseline: %v", err)
	}
	paths := make(map[string]bool)
	inPaths := false
	for _, line := range strings.Split(string(raw), "\n") {
		switch {
		case line == "paths:":
			inPaths = true
		case inPaths && strings.HasPrefix(line, "  /"):
			key := strings.TrimSuffix(strings.TrimSpace(line), ":")
			paths[key] = true
		case inPaths && line != "" && !strings.HasPrefix(line, " "):
			inPaths = false
		}
	}
	if len(paths) == 0 {
		t.Fatal("no paths parsed from baseline.yaml - the springdoc layout changed; update this scanner")
	}
	return paths
}

// TestEndpointTemplatesMatchBaseline is the contract test: every path
// the CLI composes must be declared by the served OpenAPI contract.
func TestEndpointTemplatesMatchBaseline(t *testing.T) {
	declared := baselinePaths(t)
	for _, template := range endpointTemplates {
		if !declared[template] {
			t.Errorf("CLI endpoint %q is not a path in docs/openapi/baseline.yaml", template)
		}
	}
}

